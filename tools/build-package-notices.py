"""Build the third-party notice set for the Linux AppImage (M6-14, with M6-10).

Derives the bundled-library list from the built artifact itself
(target/release/bundle/appimage/babel.AppDir), maps every native library to
the Arch package that provided it, and retains the exact upstream licence
text for each entry under docs/third-party/package-licenses/. Generates the
machine-readable manifest (package-inventory.json), the human table
(package-libraries.md) and the in-package notice file (NOTICES.md).

Only ever run on the Arch build host: host package metadata comes from
pacman, and several licence texts are read from the installed packages.
The CI gate is tools/check-package-notices.py, which needs no host
packaging tools and only reads the committed manifest.

    python3 tools/build-package-notices.py [--appdir <dir>] [--check]

--check regenerates into a temporary directory and reports drift without
writing.

The generated Markdown/JSON is byte-deterministic but not prettier-stable;
finish with `pnpm prettier --write docs/third-party/NOTICES.md
docs/third-party/package-libraries.md docs/third-party/package-inventory.json`
and rebuild the package when NOTICES.md changed, so the in-package copy
stays byte-identical to the committed source.
"""

