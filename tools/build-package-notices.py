def host_prerequisites(appdir):
    libs = Path(appdir) / "usr" / "lib"
    env = {"LD_LIBRARY_PATH": str(libs), "PATH": "/usr/bin:/bin"}
    found = {}
    targets = [appdir / "usr/bin/babel-desktop",
               libs / "webkit2gtk-4.1" / "WebKitWebProcess",
               libs / "webkit2gtk-4.1" / "WebKitNetworkProcess"]
    for target in targets:
        if not target.is_file():
            continue
        out = subprocess.run(["ldd", str(target)], capture_output=True, text=True,
                             env={**os.environ, **env}).stdout
        for line in out.splitlines():
            if "=>" not in line:
                continue
            name, _, rest = line.strip().partition("=>")
            path = rest.strip().split()[0]
            if path.startswith(str(appdir)) or path.startswith(str(libs)):
                continue
            found.setdefault(name.strip(), {"resolved": path, "neededBy": []})
            found[name.strip()]["neededBy"].append(target.name)
    return [{"name": name, "resolved": info["resolved"],
             "neededBy": sorted(set(info["neededBy"])),
             "note": "Loaded from the host; not bundled, not redistributed."}
            for name, info in sorted(found.items())]


