def run(*args):
    return subprocess.check_output(list(args), text=True).strip()


def sha256(path):
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        for chunk in iter(lambda: handle.read(65536), b""):
            digest.update(chunk)
    return digest.hexdigest()


def fetch(url, expected):
    request = urllib.request.Request(url, headers={"User-Agent": "babel-notices-tool"})
    with urllib.request.urlopen(request, timeout=60) as response:
        data = response.read()
    actual = hashlib.sha256(data).hexdigest()
    if actual != expected:
        raise SystemExit(f"Upstream fetch mismatch for {url}:\nexpected {expected}\nactual   {actual}")
    return data


def package_info(package):
    out = run("pacman", "-Qi", package)
    info = {}
    for line in out.splitlines():
        if line.startswith("Version"):
            info["version"] = line.split(":", 1)[1].strip()
        elif line.startswith("Licenses"):
            info["declared"] = line.split(":", 1)[1].strip()
        elif line.startswith("URL"):
            info["upstream"] = line.split(":", 1)[1].strip()
    return info


def find_host(basename):
    direct = Path("/usr/lib") / basename
    if direct.exists():
        return direct
    found = run("find", "/usr/lib", "-name", basename).split()
    return Path(found[0]) if found else None


def owner_of(path):
    out = run("pacman", "-Qo", str(path))
    # "... is owned by <pkg> <ver>"
    return out.rsplit("owned by", 1)[1].strip().split()[0]


def cargo_dir(crate):
    matches = sorted(Path.home().glob(f".cargo/registry/src/*/{crate}"))
    if not matches:
        raise SystemExit(f"Cargo registry source for {crate} not found")
    return matches[0]


